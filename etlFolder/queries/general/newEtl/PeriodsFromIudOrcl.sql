-- Группы, по которым в журнале есть необработанные записи.
--
-- Граница idrw обязательна и должна быть ТОЙ ЖЕ, что у пометки
-- (MarkPeriodIud*): помечаются обработанными только записи с idrw <= границы,
-- взятой в начале прогона. Без такого же условия здесь получалось, что группа
-- берётся в работу по записи, появившейся уже ПОСЛЕ границы, переносится — и
-- не помечается. Следующий прогон видел ту же запись и делал ту же группу
-- второй раз.
SELECT DISTINCT period FROM koknaev.etl_log_iud_row
WHERE isetl = 0 AND tablename = :tablename AND idrw <= :idrwBefore
