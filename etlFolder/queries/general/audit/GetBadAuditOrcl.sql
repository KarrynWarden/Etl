-- Группы линии, которые нужно проверить аудитом.
-- isokaudit:
--   1  — проверено, идентично (пропускаем);
--   4  — помечено на полную перезаливку ETL'ем (его зона, не трогаем);
--   0  — ETL перенёс группу, аудит ещё не проверял (берём);
--  -2  — прошлый аудит упал (повторяем);
--  -4  — прошлый аудит нашёл отличия (повторяем);
--  -1  — ETL-ошибка по группе (берём — пусть аудит зафиксирует факт расхождения);
--  NULL — новая группа (берём).
SELECT tablename, period
FROM koknaev.etl_jobs
WHERE tablename = :tablename
  AND (isokaudit IS NULL OR isokaudit NOT IN (1, 4))
ORDER BY period
