ANALYZE medree_prdisp;


--------------------------------------------------------------------------------
-- 5. Сверка с json-эталоном.
--
-- Перед первым прогоном имена и типы колонок ДОЛЖНЫ совпасть с
-- etlFolder/structures/MEDREE_PRDISP/medree_prdisp.json — иначе линия сразу
-- падает в FLK («структура ведомой не совпадает»). Сверка идёт по тройке
-- (column_name, data_type, numeric_scale); лишние колонки в БД допустимы,
-- отсутствующие — нет. Ровно этот запрос выполняет проверка структуры:
--
--   SELECT c.column_name, c.data_type, c.numeric_scale
--   FROM   information_schema.columns c
--   WHERE  c.table_name = 'medree_prdisp'
--   ORDER  BY c.column_name;
--
-- Ожидается: idrw integer 0, id bigint 0, groupcode smallint 0, year integer 0,
-- month integer 0. Разошлось — правь json (быстрее всего конструктором,
-- вкладка «Сложный ETL» -> пересъём структур), а не таблицу.
--
-- ВНИМАНИЕ к имени колонки группы: в Postgres она называется GROUPCODE (одна
-- «p»), в Oracle — GROUPPCODE (две). Это НЕ ошибка и чинить не нужно: ведущая и
-- ведомая сопоставляются по ПОРЯДКУ колонок в json-структурах, а не по именам.
-- Важно лишь, чтобы в каждом json стояло имя, как в своей БД, и чтобы порядок
-- колонок в обоих файлах совпадал (idrw, id, group*code, year, month).
