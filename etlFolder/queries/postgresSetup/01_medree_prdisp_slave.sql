-- Medree_prdisp: подготовка ВЕДОМОЙ таблицы в PostgreSQL под часть 2 ETL.
--
-- Сама таблица уже создана:
--   create table medree_prdisp (
--       id        bigint   not null,   -- идентификатор ЗЛ (IPerson.ID)
--       groupcode smallint not null,   -- 1 дисп. / 2 проф. / 3 центр здоровья
--       year      integer  not null,
--       month     integer
--   );
--   create index ix_medree_prdisp on medree_prdisp (id, year, groupcode);
--   alter table medree_prdisp add column idrw integer;
--   alter table medree_prdisp alter column idrw set not null;
--   alter table medree_prdisp add primary key (idrw);
--
-- Ниже — то, чего таблице не хватает для ETL. Скрипт идемпотентный.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- 1. Индекс по периоду — ОБЯЗАТЕЛЬНО.
--
-- Часть 2 обновляет группу целиком: DELETE FROM medree_prdisp
-- WHERE year = ? AND month = ?, потом заливает строки группы заново. Индекс
-- ix_medree_prdisp (id, year, groupcode) для этого не годится: year в нём не
-- ведущая колонка, month отсутствует. Без индекса ниже каждая группа = полный
-- скан ~16 млн строк, и на переносе 180 групп это часы лишнего времени.
--
-- Тот же индекс использует аудит (AuditAll): он читает ведомую за период.
--------------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS ix_medree_prdisp_ym ON medree_prdisp (year, month);


--------------------------------------------------------------------------------
-- 2. idrw: вставка значения из Oracle должна быть разрешена.
--
-- idrw переносится КАК ЕСТЬ из Oracle (это суррогатный PK ведущей). Колонка
-- заведена как обычный integer без DEFAULT — этого достаточно, ETL всегда
-- передаёт значение явно. Ничего делать не надо.
--
-- ЕСЛИ решишь повесить на неё автоинкремент для ручных вставок — только
-- BY DEFAULT, иначе ETL не сможет положить своё значение:
--     ALTER TABLE medree_prdisp
--       ALTER COLUMN idrw ADD GENERATED BY DEFAULT AS IDENTITY;   -- НЕ ALWAYS
--
-- ЗАПАС ТИПА. integer держит до 2 147 483 647. Ночной пересчёт заново выдаёт
-- idrw из oracle-последовательности всем строкам изменившегося периода, то
-- есть номера расходуются: ~16 млн ушло на первичное заполнение, дальше
-- порядка сотен тысяч в сутки на пару свежих месяцев — запас на десятилетия.
-- Но если гонять medree_prdisp_refresh(p_force => 1) регулярно, расход вырастет
-- в разы. Тогда:
--     ALTER TABLE medree_prdisp ALTER COLUMN idrw TYPE bigint;
-- и обязательно поправить data_type на bigint в
-- etlFolder/structures/MEDREE_PRDISP/medree_prdisp.json — иначе сверка структур
-- не сойдётся и линия встанет с FLK.
--------------------------------------------------------------------------------


