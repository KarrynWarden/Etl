--------------------------------------------------------------------------------
-- iprkdept: ВЕДОМАЯ таблица в PostgreSQL.
--
-- Пара к oracleSetup/11_iprkdept_createdate.sql — там объяснено, почему линия
-- переезжает с section_compare по dbeg на iud по createdate и почему ключом
-- становится idrw. Запускать ПОСЛЕ оракловой части и ДО выкладки кода:
-- структуры и конфиг из репозитория ждут createdate с обеих сторон.
--
-- Скрипт идемпотентный.
--
-- ПОРЯДОК КОЛОНОК здесь смысловой, а не алфавитный, и это безопасно: эталоны
-- (structures/IPRKDEPT/*.json) отсортированы по имени с обеих сторон, а пары
-- строятся по позиции В ЭТАЛОНАХ, не в таблице.
--------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS iprkdept (
    idrw       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                -- ключ переноса; BY DEFAULT, а НЕ ALWAYS —
                                -- иначе ETL не сможет положить своё значение
    id         bigint NOT NULL, -- идентификатор комплекта ЗЛ (IPerson.ID)
    typeprk    smallint,        -- тип прикрепления (1 — по АПП, 3 — доврачебная в ФАП)
    dbeg       date,            -- дата загрузки прикрепления
    dend       date,            -- дата загрузки открепления
    dvizit     date,            -- дата прикрепления
    ddepart    date,            -- дата открепления
    mo         integer,         -- код МО (SpMu.Code)
    otdel      numeric(4),      -- код отделения МО ОООО (SpOtdel.Code), максимум 9999
    dept       integer,         -- код участка МО УУ (SpDept.Code)
    subdept    integer,         -- код пункта/ФАП ПП (SpSubDept.Code)
    methprk    smallint,        -- способ прикрепления (1 — террит.-участк., 2 — по заявлению)
    sourcebeg  smallint,        -- источник сведений о прикреплении (1-СМО, 2-ТФОМС, 3-МО)
    sourceend  smallint,        -- источник сведений об откреплении (1-СМО, 2-ТФОМС, 3-МО)
    reason     smallint,        -- причина открепления ЗЛ (SpIPrkReason.Code)
    idlogbeg   bigint,          -- журнал загрузки о прикреплении (IPrkLog.IDLog)
    idlogend   bigint,          -- журнал загрузки об откреплении (IPrkLog.IDLog)
    lastupdate timestamp,       -- дата последнего обновления записи (пишет триггер)
    createdate date             -- период линии; заводится сразу, не ALTER'ом
);

--------------------------------------------------------------------------------
-- ПОЧЕМУ otdel — numeric(4), а не integer.
--
-- На ведущей это NUMBER со шкалой 0 (structures/IPRKDEPT/IPRKDEPT.json), и
-- сверка структур сравнивает тип со шкалой дословно. integer в Postgres
-- отдаётся как `integer`, а NUMBER — как `numeric`; типы не сойдутся, и линия
-- встанет с FLK на первом же прогоне.
--
-- Размер 4 — из постановки: код отделения не больше 9999.
--
-- Эталон ведомой (structures/IPRKDEPT/iprkdept.json) правится ВМЕСТЕ с этой
-- строкой: там должно стоять data_type `numeric`, data_scale 0.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- 1. Индекс по периоду: выборка группы, удаление группы, аудит.
--------------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS ix_iprkdept_createdate ON iprkdept (createdate);


--------------------------------------------------------------------------------
-- 2. Права переносу.
--
-- Ведомая — сюда пишут, поэтому нужны все четыре: INSERT ... ON CONFLICT
-- обновляет строку, а удаление группы делает DELETE.
--------------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON iprkdept TO etl_user;


--------------------------------------------------------------------------------
-- 3. Статистика — планировщик должен узнать про таблицу и индексы.
--------------------------------------------------------------------------------
ANALYZE iprkdept;


--------------------------------------------------------------------------------
-- 4. Сверка с json-эталоном (structures/IPRKDEPT/iprkdept.json). Ровно этот
--    запрос выполняет проверка структуры перед каждым прогоном; расхождение —
--    это FLK и остановка линии.
--------------------------------------------------------------------------------
SELECT c.column_name, c.data_type, c.numeric_scale
  FROM information_schema.columns c
 WHERE c.table_name = 'iprkdept'
 ORDER BY c.column_name;


--------------------------------------------------------------------------------
-- ЕСЛИ ТАБЛИЦА УЖЕ БЫЛА ЗАВЕДЕНА РАНЬШЕ, без createdate и без ключа на idrw.
--
-- CREATE TABLE IF NOT EXISTS такую таблицу не тронет — она останется прежней, и
-- линия встанет с FLK. Тогда выполнить блок ниже ОДИН раз; на свежей таблице он
-- не нужен вовсе.
--
--   -- обе цифры должны быть 0, иначе сперва разобраться с данными:
--   SELECT count(*) AS idrw_null FROM iprkdept WHERE idrw IS NULL;
--   SELECT count(*) AS idrw_dup FROM (
--       SELECT idrw FROM iprkdept GROUP BY idrw HAVING count(*) > 1) d;
--
--   ALTER TABLE iprkdept ADD COLUMN IF NOT EXISTS createdate date;
--   UPDATE iprkdept SET createdate = lastupdate::date WHERE createdate IS NULL;
--   ALTER TABLE iprkdept ALTER COLUMN idrw SET NOT NULL;
--   CREATE UNIQUE INDEX IF NOT EXISTS uq_iprkdept_idrw ON iprkdept (idrw);
--   ANALYZE iprkdept;
--
-- createdate заполняется тем же правилом, что и на ведущей — днём lastupdate.
-- Значения обязаны совпасть с точностью до строки, иначе первый же аудит
-- объявит расхождением всю таблицу. Совпадут они потому, что сам lastupdate уже
-- перенесён ETL и на обеих сторонах одинаков.
--
-- Уникальность idrw обязательна: запись идёт `INSERT ... ON CONFLICT (idrw)
-- DO UPDATE`, а ON CONFLICT требует именно уникального индекса по колонке.
-- Старый первичный ключ (dbeg, id, typeprk) НЕ трогаем: он ничему не мешает,
-- а его снятие — отдельное решение, и принимать его в момент переключения
-- режима переноса не стоит.
--------------------------------------------------------------------------------
