-- reqprepmomocheck: индекс под разбор зависимости (PostgreSQL).
--
-- Линия reqprepmomocheck объявляет зависимость от REQPREPSMO (см. ключ
-- iudDependencies в etlFolder/config.d/reqprepmomocheckPostPost.json). На каждом
-- прогоне, когда в журнале есть метка 'fublin', перенос дважды спрашивает связь
-- по REQPREPSMO_idrw:
--
--   1) что запрос линии отдаёт СЕЙЧАС — SELECT ... FROM ( запрос ) p
--      WHERE p.reqprepsmo_idrw IN (...);
--   2) что вообще СВЯЗАНО с этими ключами — SELECT ... FROM reqprepmo
--      WHERE reqprepsmo_idrw IN (...).
--
-- Разница между списками и есть «строки, выпавшие из выборки»: связь осталась,
-- а условию (s.DIRDT IS NOT NULL) строка больше не отвечает — такие удаляются
-- из ведомой.
--
-- Без индекса второй запрос — полный скан reqprepmo на КАЖДОМ прогоне, а даг
-- ходит раз в минуту. Первый запрос индекс тоже использует: планировщик
-- проталкивает условие внутрь подзапроса, потому что p.reqprepsmo_idrw — голая
-- колонка, не спрятанная под функцию.
--
-- Скрипт идемпотентный.
--------------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS ix_reqprepmo_reqprepsmo_idrw
    ON reqprepmo (reqprepsmo_idrw);

ANALYZE reqprepmo;


